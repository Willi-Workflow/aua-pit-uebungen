// Mit dominant-baseline: middle liegt die Grundlinie 2,7 unter der Zeilenmitte (in Chrome gemessen)
export const GRUNDLINIE = 2.7;

// Tinte einer Zeile im Koordinatensystem des Textelements, Zeile bei "dy",
// "anker" 'mitte' (text-anchor: middle) oder 'start'
export function zeileTinte(text, fett, anker, dy) {
  const tabelle = GLYPHEN[fett ? 'fett' : 'normal'];
  const zeichen = [...text];
  const glyph = (z) => tabelle[z] || tabelle.W; // Unbekanntes wie ein breites Zeichen
  let vorschub = 0; let oben = 0; let unten = 0;
  for (const z of zeichen) {
    const g = glyph(z);
    vorschub += g[0];
    if (z !== ' ') { oben = Math.max(oben, g[1]); unten = Math.max(unten, g[2]); }
  }
  const erstes = glyph(zeichen[0]);
  const letztes = glyph(zeichen[zeichen.length - 1]);
  const anfang = anker === 'mitte' ? -vorschub / 2 : 0;
  return { text, x0: anfang - erstes[3], x1: anfang + vorschub - (letztes[0] - letztes[4]), y0: dy + GRUNDLINIE - oben, y1: dy + GRUNDLINIE + unten };
}

// Tinte aller Texte eines Blatts im Koordinatensystem ihres Textelements
export function tinteMessen(texte) {
  return texte.map((t) => {
    const anker = t.klasse === 'gate' ? 'start' : 'mitte';
    const fett = t.klasse === 'nord' || t.klasse === 'fett';
    let dy = 0;
    return { klasse: t.klasse, zeilen: t.zeilen.map((text, i) => { dy += i === 0 ? 0 : (t.dys[i] ?? 9); return zeileTinte(text, fett, anker, dy); }) };
  });
}

// Tinte einer Textzeile als Polygon in Blattkoordinaten
export function tintenPolygon(t, z) {
  const ecken = [{ x: z.x0, y: z.y0 }, { x: z.x1, y: z.y0 }, { x: z.x1, y: z.y1 }, { x: z.x0, y: z.y1 }];
  return ecken.map((p) => anwenden(t, p));
}
